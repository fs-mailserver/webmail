"""Render the initial Alembic migration from model metadata without a live DB.

Uses Alembic's own autogenerate renderer with the PostgreSQL dialect (same output as
`alembic revision --autogenerate` against an empty database).

    cd backend && python scripts/render_initial_migration.py > alembic/versions/<file>.py
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from alembic.autogenerate import render_python_code  # noqa: E402
from alembic.operations import ops  # noqa: E402
from alembic.runtime.migration import MigrationContext  # noqa: E402

from app.models import Base  # noqa: E402

REVISION = "0001_initial"


def build_ops() -> tuple[ops.UpgradeOps, ops.DowngradeOps]:
    upgrade_ops: list[ops.MigrateOperation] = []
    downgrade_ops: list[ops.MigrateOperation] = []
    tables = Base.metadata.sorted_tables
    for table in tables:
        upgrade_ops.append(ops.CreateTableOp.from_table(table))
        for index in sorted(table.indexes, key=lambda i: i.name or ""):
            upgrade_ops.append(ops.CreateIndexOp.from_index(index))
    for table in reversed(tables):
        for index in sorted(table.indexes, key=lambda i: i.name or ""):
            downgrade_ops.append(ops.DropIndexOp.from_index(index))
        downgrade_ops.append(ops.DropTableOp.from_table(table))
    return ops.UpgradeOps(ops=upgrade_ops), ops.DowngradeOps(ops=downgrade_ops)


def main() -> None:
    ctx = MigrationContext.configure(dialect_name="postgresql", opts={"target_metadata": Base.metadata})
    up_ops, down_ops = build_ops()
    imports: set[str] = set()
    up = render_python_code(up_ops, migration_context=ctx, imports=imports)
    down = render_python_code(down_ops, migration_context=ctx, imports=imports)
    up, down = (
        "\n".join(line if line.startswith("    ") or not line else "    " + line for line in code.splitlines())
        for code in (up, down)
    )
    import_lines = "\n".join(sorted(imports))
    print(f'''"""initial schema: users, accounts, mail index, blocklist, devices

Revision ID: {REVISION}
Revises:
Create Date: 2026-11-12 22:30:00

Generated by scripts/render_initial_migration.py (Alembic autogenerate renderer).
"""
from collections.abc import Sequence

import sqlalchemy as sa
from alembic import op
from sqlalchemy.dialects import postgresql
{import_lines}

revision: str = "{REVISION}"
down_revision: str | None = None
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None


def upgrade() -> None:
    op.execute("CREATE EXTENSION IF NOT EXISTS pgcrypto")  # gen_random_uuid() on PG < 13; no-op on 13+
{up}


def downgrade() -> None:
{down}
''')


if __name__ == "__main__":
    main()
